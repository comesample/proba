/* 웹 기능 판정 — 실행 행(t)의 원인 + 담당자 확정(run.judged) */
export const judgeWeb = (run, t) => {
  if (!t || t.v !== "FAIL") return null;
  const cause = t.cause || "판정 불가";
  const base = WEB_CAUSE[cause] || WEB_CAUSE["판정 불가"];
  const fixed = ((run && run.judged) || {})[t.id];
  return { ...base, cause, kind: fixed || base.kind, fixed: !!fixed };
};
